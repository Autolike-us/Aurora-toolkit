-- Aurora database (MySQL 5.7+ / MariaDB). Run once in cPanel > phpMyAdmin > SQL on your new database.
CREATE TABLE IF NOT EXISTS users (
  id VARCHAR(32) NOT NULL PRIMARY KEY,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  email_verified_at DATETIME NULL,
  created_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sessions (
  token_hash CHAR(64) NOT NULL PRIMARY KEY,
  user_id VARCHAR(32) NOT NULL,
  created_at DATETIME NOT NULL,
  expires_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS email_tokens (
  token_hash CHAR(64) NOT NULL PRIMARY KEY,
  user_id VARCHAR(32) NOT NULL,
  purpose VARCHAR(16) NOT NULL,
  expires_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS licenses (
  id VARCHAR(32) NOT NULL PRIMARY KEY,
  user_id VARCHAR(32) NOT NULL UNIQUE,
  license_key VARCHAR(20) NOT NULL UNIQUE,
  trial_started_at DATETIME NOT NULL,
  trial_ends_at DATETIME NOT NULL,
  created_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS subscriptions (
  id VARCHAR(32) NOT NULL PRIMARY KEY,
  user_id VARCHAR(32) NOT NULL,
  provider VARCHAR(10) NOT NULL,
  provider_sub_id VARCHAR(100) NOT NULL,
  provider_customer_id VARCHAR(100) NULL,
  plan VARCHAR(12) NOT NULL,
  status VARCHAR(20) NOT NULL,
  current_period_end DATETIME NULL,
  launch_price TINYINT NOT NULL DEFAULT 0,
  cancel_at_period_end TINYINT NOT NULL DEFAULT 0,
  updated_at DATETIME NOT NULL,
  created_at DATETIME NOT NULL,
  UNIQUE KEY uniq_provider_sub (provider, provider_sub_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS activations (
  id VARCHAR(32) NOT NULL PRIMARY KEY,
  license_id VARCHAR(32) NOT NULL,
  install_id VARCHAR(80) NOT NULL,
  product VARCHAR(12) NOT NULL,
  first_seen DATETIME NOT NULL,
  last_seen DATETIME NOT NULL,
  UNIQUE KEY uniq_activation (license_id, install_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS webhook_events (
  id VARCHAR(100) NOT NULL PRIMARY KEY,
  provider VARCHAR(10) NOT NULL,
  received_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS rate_limits (
  k CHAR(64) NOT NULL PRIMARY KEY,
  window_start DATETIME NOT NULL,
  hits INT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS reply_usage (
  k CHAR(64) NOT NULL,
  ym CHAR(7) NOT NULL,
  n INT NOT NULL DEFAULT 0,
  updated_at DATETIME NOT NULL,
  PRIMARY KEY (k, ym)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS reply_usage_day (k CHAR(64) NOT NULL, d CHAR(10) NOT NULL, n INT NOT NULL DEFAULT 0, PRIMARY KEY (k, d)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS reply_accounts (user_id VARCHAR(32) NOT NULL PRIMARY KEY, trial_started_at DATETIME NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS reply_packs (id VARCHAR(32) NOT NULL PRIMARY KEY, user_id VARCHAR(32) NOT NULL, replies_total INT NOT NULL, replies_left INT NOT NULL, expires_at DATETIME NOT NULL, source VARCHAR(24) NOT NULL, created_at DATETIME NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS reply_cost (ym CHAR(7) NOT NULL, model VARCHAR(48) NOT NULL, plan VARCHAR(16) NOT NULL, reqs INT NOT NULL DEFAULT 0, replies INT NOT NULL DEFAULT 0, tok_in BIGINT NOT NULL DEFAULT 0, tok_out BIGINT NOT NULL DEFAULT 0, PRIMARY KEY (ym, model, plan)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
